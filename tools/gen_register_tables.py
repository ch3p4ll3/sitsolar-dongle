#!/usr/bin/env python3
"""Emit the register map as Markdown tables, straight from registers.py.

The tables under the "Full map" heading in docs/protocol/registers.md are
generated by this script so the documentation cannot drift from the
implementation.

Usage:
    python tools/gen_register_tables.py

Regenerate the section by splicing the output between the "## Full map"
heading and the "## Where the document disagrees with the hardware" heading of
docs/protocol/registers.md.

The module is loaded directly from its file path rather than imported as part of
the package, so that building the docs does not require pycryptodome to be
installed.
"""

from __future__ import annotations

import importlib.util
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REGISTERS_PY = ROOT / "src" / "sitsolar_dongle" / "registers.py"


def load_registers():
    spec = importlib.util.spec_from_file_location("registers", REGISTERS_PY)
    if spec is None or spec.loader is None:
        raise SystemExit("cannot load %s" % REGISTERS_PY)
    module = importlib.util.module_from_spec(spec)
    # dataclasses resolves string annotations through sys.modules
    sys.modules["registers"] = module
    spec.loader.exec_module(module)
    return module


def esc(text: str) -> str:
    return text.replace("|", "\\|")


def note_for(reg) -> str:
    parts = []
    if reg.notes:
        parts.append(esc(reg.notes))
    if reg.enum:
        parts.append("%d enum labels" % len(reg.enum))
    if reg.bits:
        parts.append("%d named bits" % len(reg.bits))
    return ". ".join(parts)


def main() -> int:
    mod = load_registers()
    registers = mod.REGISTERS
    sections = mod.SECTION_RANGES

    by_section: dict[str, list] = {name: [] for _, _, name in sections}
    for reg in registers:
        by_section[reg.section].append(reg)

    for lo, hi, name in sections:
        regs = by_section[name]
        print("\n### %s\n" % name)
        print("`%d\u2013%d` \u2014 %d value(s)\n" % (lo, hi, len(regs)))
        print("| Address | Key | Name | Type | Scale | Unit | Notes |")
        print("|---|---|---|---|---|---|---|")
        for reg in regs:
            scale = "" if reg.scale == 1.0 else "`%g`" % reg.scale
            unit = esc(reg.unit) if reg.unit else ""
            dtype = "ASCII (%d)" % reg.length if reg.dtype == mod.ASCII else reg.dtype
            print("| `%s` | `%s` | %s | %s | %s | %s | %s |" % (
                reg.span, reg.key, esc(reg.name), dtype, scale, unit,
                note_for(reg)))
        print()

    blocks = mod.blocks()
    print("\n**Totals**: %d values across %d read ranges.\n"
          % (len(registers), len(blocks)))
    print("Coalesced read ranges:\n")
    print("```text")
    print(", ".join("%d\u2013%d" % (start, end) for start, end in blocks))
    print("```")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
